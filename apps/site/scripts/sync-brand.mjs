// Copies the built logo files into this app. The brand build (packages/brand/build.mjs) still writes
// into the dashboard's public/brand; run this after `npm run brand`. Writes lib/brand-files.ts.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../../..')
const web = ['apps/web', '.'].map((d) => resolve(repo, d)).find((d) => existsSync(resolve(d, 'src/ui/brand-files.ts')))
if (!web) throw new Error('brand-files.ts not found: run `npm run brand` first')
const src = readFileSync(resolve(web, 'src/ui/brand-files.ts'), 'utf8')
const files = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1))
mkdirSync(resolve(here, '../public/brand'), { recursive: true })
for (const [key, path] of Object.entries(files)) {
  if (typeof path === 'string') copyFileSync(resolve(web, 'public', path.slice(1)), resolve(here, '../public', path.slice(1)))
}
writeFileSync(resolve(here, '../lib/brand-files.ts'), `// Generated by scripts/sync-brand.mjs from the dashboard's brand build. Do not edit.\nexport const BRAND = ${JSON.stringify(files, null, 2)} as const\n`)
console.log('brand files synced:', Object.keys(files).join(', '))
