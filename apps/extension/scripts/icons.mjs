// Writes apps/extension/icons.js: the Lucide icons the popup and options page use, as inline SVG strings (the
// extension has no build step). Add a name below and run: npm run icons -w apps/extension
import { readFileSync, writeFileSync } from 'node:fs'

const ICONS = {
  settings: 'settings', back: 'arrow-left', open: 'arrow-up-right', plus: 'plus', check: 'check', pause: 'pause', play: 'play',
  eyeOff: 'eye-off', eye: 'eye', course: 'graduation-cap', show: 'tv', video: 'square-play', book: 'book-open', other: 'bookmark',
  shield: 'shield-check', flame: 'flame', snowflake: 'snowflake', sparkles: 'sparkles', enter: 'corner-down-left', trash: 'trash-2',
  refresh: 'refresh-cw', keyboard: 'keyboard', swords: 'swords', x: 'x', sliders: 'sliders-horizontal', clock: 'clock',
}

const svg = (node) => {
  const kids = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}></${tag}>`).join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${kids}</svg>`
}

/** An icon's drawing; renamed icons (trash-2 → trash) re-export the new name, so follow that. */
function nodeOf(file) {
  const src = readFileSync(new URL(`../../../node_modules/lucide-react/dist/esm/icons/${file}.mjs`, import.meta.url), 'utf8')
  const alias = /export \{ default \} from '\.\/(.+)\.mjs'/.exec(src)
  if (alias) return nodeOf(alias[1])
  const m = /const __iconData = (\{[\s\S]*?\n\});/.exec(src)
  if (!m) throw new Error(`No icon data in ${file}`)
  return Function(`return (${m[1]})`)().node
}

const out = Object.fromEntries(Object.entries(ICONS).map(([key, file]) => [key, svg(nodeOf(file))]))
writeFileSync(new URL('../icons.js', import.meta.url),
  `// Lucide icons (ISC licence) used by the popup and options page, as inline SVG. Generated by scripts/icons.mjs.\nself.ICON = ${JSON.stringify(out, null, 2)}\n`)
console.log(`apps/extension/icons.js: ${Object.keys(out).length} icons`)
