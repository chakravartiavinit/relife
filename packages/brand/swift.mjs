// Writes apps/mac/Sources/ReLifeKit/Brand.swift from brand.json (name, shortName, tagline), the way
// packages/tokens writes Tokens.swift. Usage: node packages/brand/swift.mjs [--check]
// --check exits 1 if the committed file differs (also run by `npm run brand:check`, so pre-push covers it).
// It lives in ReLifeKit, not the app, because the Kit's own strings ("Can't reach your ...") need the name too.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../..')
const brand = JSON.parse(readFileSync(resolve(here, 'brand.json'), 'utf8'))
export const swiftPath = resolve(repo, 'apps/mac/Sources/ReLifeKit/Brand.swift')

const lit = (s) => JSON.stringify(s)

export const swiftText = () => `// Generated by packages/brand/swift.mjs from brand.json. Do not edit; run \`npm run brand:swift\`.
// build.sh and tools/*.sh read \`name\` from this file (tools/env.sh), so the product name is typed in one place.

/// The product's name and tagline, from packages/brand/brand.json.
public enum Brand {
    public static let name = ${lit(brand.name)}
    public static let shortName = ${lit(brand.shortName)}
    public static let tagline = ${lit(brand.tagline)}
}
`

/** True when the committed Brand.swift matches brand.json. */
export const swiftIsFresh = () => existsSync(swiftPath) && readFileSync(swiftPath, 'utf8') === swiftText()

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (!swiftIsFresh()) {
      console.error(`brand: ${relative(repo, swiftPath)} is out of date (run \`npm run brand:swift\`)`)
      process.exit(1)
    }
    console.log('brand: Brand.swift up to date')
  } else {
    mkdirSync(dirname(swiftPath), { recursive: true })
    writeFileSync(swiftPath, swiftText())
    console.log(`brand: wrote ${relative(repo, swiftPath)}`)
  }
}
