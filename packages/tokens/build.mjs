// Writes every output of tokens.json. Usage: node packages/tokens/build.mjs [--check]
// --check regenerates in memory and exits 1 if a committed file differs (run by pre-push).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { converter, toGamut, parse } from 'culori'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../..')
const tokens = JSON.parse(readFileSync(resolve(here, 'tokens.json'), 'utf8'))

/** Where each output lives. The extension has no bundler, so it gets its own copy. */
const OUT = {
  css: resolve(here, 'tokens.css'),
  theme: resolve(here, 'theme.css'),
  extension: resolve(repo, 'apps/extension/tokens.css'),
  swift: resolve(repo, 'apps/mac/Sources/ReLife/UI/Tokens.swift'),
  kotlin: resolve(repo, 'apps/android/app/src/main/java/com/relife/android/ui/Tokens.kt'),
}

const HEADER = 'Generated by packages/tokens/build.mjs from tokens.json. Do not edit; run `npm run tokens`.'
const note = (t) => (t.note ? `  /* ${t.note} */` : '')
const swiftNote = (t) => (t.note ? `  // ${t.note}` : '')
const curve = (c) => `cubic-bezier(${c.join(', ')})`

/** One `--name: value;` line per token of a group, for the given theme (null = skip tokens without a dark value). */
function decls(theme) {
  const lines = []
  const pick = (group, name, t) => {
    const value = theme === 'dark' ? t.dark : t.light
    if (value !== undefined) lines.push(`  --${name}: ${value};${theme === 'dark' ? '' : note(t)}`)
  }
  for (const [group, label] of [['color', null], ['shadow', 'Elevation: layered transparent shadows, no borders'], ['effect', 'Canvas and texture']]) {
    if (label && theme === 'light') lines.push('', `  /* ${label} */`)
    else if (label) lines.push('')
    for (const [name, t] of Object.entries(tokens[group])) pick(group, name, t)
  }
  if (theme === 'light') {
    lines.push('', '  /* Motion */')
    for (const [name, t] of Object.entries(tokens.ease)) lines.push(`  --ease-${name}: ${curve(t.curve)};${note(t)}`)
  }
  return lines.join('\n').replace(/\n{2,}(?=\n)/g, '\n\n').replace(/^\n+/, '')
}

function css() {
  const dark = decls('dark').replace(/^\n+/, '')
  return `/* ${HEADER} */
:root {
  color-scheme: light;

${decls('light')}
}

[data-theme="dark"] {
  color-scheme: dark;

${dark}
}

/* Surfaces without the theme script (the extension) follow the system. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;

${dark.replace(/^(?=.)/gm, '  ')}
  }
}
`
}

/** Tailwind's theme scale for web and site: radii and easings become utilities (rounded-lg, ease-out-quint). */
function theme() {
  const r = Object.entries(tokens.radius).map(([k, t]) => `  --radius-${k}: ${t.px}px;${note(t)}`)
  const e = Object.entries(tokens.ease).map(([k, t]) => `  --ease-${k}: ${curve(t.curve)};${note(t)}`)
  return `/* ${HEADER} */
@theme inline {
  /* Concentric radius scale: outer = inner + padding */
${r.join('\n')}

${e.join('\n')}
}
`
}

// oklch -> Display P3 (what the Mac app's colors are defined in).
const toP3 = converter('p3')
function p3(value) {
  const c = parse(value)
  if (!c) throw new Error(`Cannot parse color ${value}`)
  const { r, g, b, alpha = 1 } = toP3(toGamut('p3', 'oklch')(c))
  const n = (x) => Number(Math.min(1, Math.max(0, x)).toFixed(4))
  return `P3(${n(r)}, ${n(g)}, ${n(b)}${alpha < 1 ? `, ${n(alpha)}` : ''})`
}
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase())

function swift() {
  const colors = Object.entries(tokens.color).map(([name, t]) => {
    const light = p3(t.light), dark = t.dark ? p3(t.dark) : null
    return `    static let ${camel(name)} = ${dark ? `dynamic(light: ${light}, dark: ${dark})` : `Color(${light})`}${swiftNote(t)}`
  })
  const radii = Object.entries(tokens.radius).map(([k, t]) => `    static let ${camel('radius-' + k)}: CGFloat = ${t.px}${swiftNote(t)}`)
  const eases = Object.entries(tokens.ease).map(([k, t]) =>
    `    static func ${camel(k)}(_ duration: Double = 0.2) -> Animation { .timingCurve(${t.curve.join(', ')}, duration: duration) }${swiftNote(t)}`)
  return `// ${HEADER}
import SwiftUI
import AppKit

/// A Display P3 color with alpha.
struct P3: Sendable {
    var r, g, b, a: Double
    init(_ r: Double, _ g: Double, _ b: Double, _ a: Double = 1) { (self.r, self.g, self.b, self.a) = (r, g, b, a) }
}

extension Color {
    init(_ c: P3) { self.init(.displayP3, red: c.r, green: c.g, blue: c.b, opacity: c.a) }
}

enum Tokens {
    /// Follows the window's appearance, like the web's [data-theme].
    static func dynamic(light: P3, dark: P3) -> Color {
        Color(nsColor: NSColor(name: nil) { appearance in
            let c = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
            return NSColor(displayP3Red: c.r, green: c.g, blue: c.b, alpha: c.a)
        })
    }

${colors.join('\n')}

${radii.join('\n')}

${eases.join('\n')}
}
`
}

// oklch -> sRGB (what Compose's Color(0xAARRGGBB) is).
const toRgb = converter('rgb')
function argb(value) {
  const c = parse(value)
  if (!c) throw new Error(`Cannot parse color ${value}`)
  const { r, g, b, alpha = 1 } = toRgb(toGamut('rgb', 'oklch')(c))
  const byte = (x) => Math.round(Math.min(1, Math.max(0, x)) * 255).toString(16).toUpperCase().padStart(2, '0')
  return `Color(0x${byte(alpha)}${byte(r)}${byte(g)}${byte(b)})`
}

function kotlin() {
  const colors = Object.entries(tokens.color).map(([name, t]) =>
    `    val ${camel(name)} = ThemeColor(${argb(t.light)}, ${argb(t.dark ?? t.light)})${swiftNote(t)}`)
  const radii = Object.entries(tokens.radius).map(([k, t]) => `    val ${camel('radius-' + k)} = ${t.px}.dp${swiftNote(t)}`)
  return `// ${HEADER}
package com.relife.android.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/** One token, both looks. A color without a dark value keeps its light value in dark mode. */
class ThemeColor(val light: Color, val dark: Color) {
    fun of(isDark: Boolean): Color = if (isDark) dark else light
}

object Tokens {
${colors.join('\n')}

${radii.join('\n')}
}
`
}

const outputs = [
  [OUT.kotlin, kotlin()],
  [OUT.css, css()],
  [OUT.theme, theme()],
  [OUT.extension, css()],
  [OUT.swift, swift()],
]

const check = process.argv.includes('--check')
const rel = (p) => relative(repo, p)
const stale = []
for (const [path, text] of outputs) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== text) stale.push(rel(path))
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
  }
}
if (check) {
  if (stale.length) {
    console.error(`tokens: out of date (run \`npm run tokens\`):\n${stale.map((s) => `  ${s}`).join('\n')}`)
    process.exit(1)
  }
  console.log('tokens: up to date')
} else {
  console.log(`tokens: wrote ${outputs.map(([p]) => rel(p)).join(', ')}`)
}
